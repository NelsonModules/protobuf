     'Layout', 'columns', 'Delimited', true), ...
    'column "label" must have 2 rows.'
  };
for k = 1:size(cases, 1)
  try
    action = cases{k, 1};
    action();
    error('test:conversion', 'no error for %s', func2str(cases{k, 1}));
  catch err
    if ~contains(err.message, cases{k, 2})
      error('test:conversion', 'For %s\n  expected: %s\n  got: %s', func2str(cases{k, 1}), cases{k, 2}, ...
        err.message);
    end
  end
end
