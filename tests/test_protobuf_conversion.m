% Errors on values.
cases = {
  @() protobuf.encode(sch, 'SensorSample', 3), ...
    'message values must be given as a struct.'
  @() protobuf.encode(sch, 'SensorSample', struct('nope', 1)), ...
    'unknown field "nope" for message "nelson.test.sensors.SensorSample".'
  @() protobuf.encode(sch, 'SensorSample', struct('timestamp_ms', {1, 2})), ...
    'A single message needs a scalar struct; use ''Delimited'' for several records.'
  @() protobuf.encode(sch, 'SensorSample', struct('diagnostics', struct('drift', {1, ...
     2}))), ...
    'field "diagnostics" expects a scalar struct.'
  @() protobuf.encode(sch, 'SensorSample', struct('diagnostics', 5)), ...
    'field "diagnostics" expects a scalar struct.'
  @() protobuf.encode(sch, 'AllTypes', struct('samples', 5)), ...
    'field "samples" expects a struct array.'
  @() protobuf.encode(sch, 'AllTypes', struct('f_string', 5)), ...
    'field "f_string" expects text.'
  @() protobuf.encode(sch, 'AllTypes', struct('f_bytes', 5)), ...
    'field "f_bytes" expects a uint8 vector or text.'
  @() protobuf.encode(sch, 'AllTypes', struct('f_int32', 'x')), ...
    'field "f_int32" expects real numeric values.'
  @() protobuf.encode(sch, 'AllTypes', struct('f_enum', 'PURPLE')), ...
    '"PURPLE" is not a value of enum "nelson.test.sensors.AllTypes.Color".'
  @() protobuf.encode(sch, 'AllTypes', struct('choice', 'f_int32')), ...
    '"f_int32" is not a member of oneof "choice".'
  @() protobuf.encode(sch, 'AllTypes', struct('c_int32', 1, 'c_string', 'a')), ...
    'oneof "choice"'
  @() protobuf.encode(sch, 'AllTypes', struct('f_int32', 1, 'UnknownFields', 5)), ...
     ...
    'UnknownFields expects a uint8 vector.'
  @() protobuf.encode(wkt, 'Reading', struct('at', [datetime(2026,1,1), datetime(2026, ...
    1,2)])), ...
    'field "at" expects a scalar value.'
  @() protobuf.encode(wkt, 'Reading', struct('marks', [datetime(2026,1,1), NaT])), ...
     ...
    'field "marks" cannot hold missing values (NaT or NaN).'
  @() protobuf.encode(wkt, 'Reading', struct('at', 5)), ...
    'field "at" expects a datetime value or a struct.'
  @() protobuf.encode(wkt, 'Reading', struct('at', datetime(2026,1,1,'TimeZone','Europe/Paris'))), ...
     ...
    'field "at" expects UTC datetime values (or no time zone).'
  @() protobuf.encode(wkt, 'Reading', struct('level', [1 2])), ...
    'field "level" expects a scalar value.'
  @() protobuf.encode(wkt, 'Reading', struct('label', {{'a', 'b'}})), ...
    'field "label" expects a scalar value.'
  @() protobuf.encode(sch, 'SensorSample', struct('status', [1; 2]), 'Layout', 'columns'), ...
     ...
    'A single message needs a scalar struct'
  @() protobuf.encode(sch, 'SensorSample', 5, 'Layout', 'columns'), ...
    'The columns layout needs a scalar struct of Nx1 columns.'
  @() protobuf.encode(sch, 'SensorSample', struct('status', [1; 2], 'timestamp_ms', ...
     [1; 2; 3]), 'Layout', 'columns', 'Delimited', true), ...
    'column "timestamp_ms" must have 2 rows.'
  @() protobuf.encode(sch, 'SensorSample', struct('status', [1; 2], 'diagnostics', ...
     struct('drift', [1; 2; 3])), 'Layout', 'columns', 'Delimited', true), ...
    'the columns of sub-message "nelson.test.sensors.SensorSample.Diagnostics" must have 2 rows.'
  @() protobuf.encode(sch, 'SensorSample', struct('status', [1; 2], 'diagnostics', ...
     5), 'Layout', 'columns', 'Delimited', true), ...
    'column "diagnostics" must have 2 rows.'
  @() protobuf.encode(sch, 'AllTypes', struct('f_int32', [1; 2], 'f_string', ["a"; "b"; "c"]), ...
     'Layout', 'columns', 'Delimited', true), ...
    'column "f_string" must have 2 rows.'
  @() protobuf.encode(sch, 'AllTypes', struct('f_int32', [1; 2], 'f_string', [5; 6]), ...
     'Layout', 'columns', 'Delimited', true), ...
    'column "f_string" expects an Nx1 cell or string array.'
  @() protobuf.encode(sch, 'AllTypes', struct('f_int32', [1; 2], 'f_double', {{1; 2}}), ...
     'Layout', 'columns', 'Delimited', true), ...
    'column "f_double" expects real numeric values.'
