% Nelson values <-> messages: every scalar type from double and single columns, wrappers,
% missing values, unknown fields with a field selection, and the errors on bad values.
%=============================================================================
DATA = [modulepath('protobuf'), '/tests/data'];
sch = protobuf.load([DATA, '/sensor_stream.proto']);
%=============================================================================
% Columns of every numeric type given as double, then as single: rounded and saturated like
% int32(), NaN as absent.
numeric = {'f_double', 'f_float', 'f_int32', 'f_int64', 'f_uint32', 'f_uint64', 'f_sint32', ...
  'f_sint64', 'f_fixed32', 'f_fixed64', 'f_sfixed32', 'f_sfixed64', 'f_bool'};
values = [1.5; -2.5; 3e20; -3e20; 0];
expected = struct('f_double', values, 'f_float', single(values), ...
  'f_int32', int32([2; -3; intmax('int32'); intmin('int32'); 0]), ...
  'f_int64', int64([2; -3; intmax('int64'); intmin('int64'); 0]), ...
  'f_uint32', uint32([2; 0; intmax('uint32'); 0; 0]), ...
  'f_uint64', uint64([2; 0; intmax('uint64'); 0; 0]), ...
  'f_sint32', int32([2; -3; intmax('int32'); intmin('int32'); 0]), ...
  'f_sint64', int64([2; -3; intmax('int64'); intmin('int64'); 0]), ...
  'f_fixed32', uint32([2; 0; intmax('uint32'); 0; 0]), ...
  'f_fixed64', uint64([2; 0; intmax('uint64'); 0; 0]), ...
  'f_sfixed32', int32([2; -3; intmax('int32'); intmin('int32'); 0]), ...
  'f_sfixed64', int64([2; -3; intmax('int64'); intmin('int64'); 0]), ...
  'f_bool', [true; true; true; true; false]);
for asSingle = [false true]
  C = struct();
  for k = 1:numel(numeric)
    if asSingle
      C.(numeric{k}) = single(values);
    else
      C.(numeric{k}) = values;
    end
  end
  R = protobuf.decode(sch, 'AllTypes', protobuf.encode(sch, 'AllTypes', C, 'Layout', 'columns', 'Delimited', true), ...
    'Delimited', true, 'Layout', 'columns', 'Fields', numeric);
  for k = 1:numel(numeric)
    want = expected.(numeric{k});
    if asSingle && any(strcmp(numeric{k}, {'f_double'}))
      want = double(single(values));
    end
    asserts.isequal(R.(numeric{k}), want);
  end
end
% Integers and logical values in their own class.
C = struct('f_int32', int8([1; -2]), 'f_uint64', uint16([3; 4]), 'f_bool', [true; false], 'f_double', int32([5; 6]));
R = protobuf.decode(sch, 'AllTypes', protobuf.encode(sch, 'AllTypes', C, 'Layout', 'columns', 'Delimited', true), ...
  'Delimited', true, 'Layout', 'columns', 'Fields', fieldnames(C));
asserts.isequal([double(R.f_int32), double(R.f_uint64), double(R.f_bool), R.f_double], [1 3 1 5; -2 4 0 6]);
% Missing values of optional fields as NaN, for every type that can be missing.
optionalFields = {'o_double', 'o_float', 'o_int64', 'o_uint32', 'o_sint64', 'o_bool', 'o_enum'};
C = struct('o_double', [1; NaN], 'o_float', single([2; NaN]), 'o_int64', [3; NaN], 'o_uint32', [4; NaN], ...
  'o_sint64', [-5; NaN], 'o_bool', [1; NaN], 'o_enum', [1; NaN]);
bytes = protobuf.encode(sch, 'AllTypes', C, 'Layout', 'columns', 'Delimited', true);
[R, P] = protobuf.decode(sch, 'AllTypes', bytes, 'Delimited', true, 'Layout', 'columns', 'MissingAsNaN', true, ...
  'Fields', optionalFields);
for k = 1:numel(optionalFields)
  asserts.isequal(double(R.(optionalFields{k})(1)), double(C.(optionalFields{k})(1)));
  asserts.istrue(isnan(R.(optionalFields{k})(2)));
  asserts.isequal(P.(optionalFields{k}), [true; false]);
end
R = protobuf.decode(sch, 'AllTypes', bytes, 'Delimited', true, 'Layout', 'columns', 'Fields', {'o_int64', 'o_bool'});
asserts.isequal(R.o_int64, int64([3; 0]));
asserts.isequal(R.o_bool, [true; false]);
% Text and bytes columns: cells, string arrays, empty rows.
C = struct('f_string', {{'a'; ''}}, 'f_bytes', {{uint8([1 2]); uint8([])}}, 'o_string', ["x"; ""], ...
  'r_string', {{{'p', 'q'}; {}}}, 'r_bytes', {{{uint8(1), 'z'}; {}}});
R = protobuf.decode(sch, 'AllTypes', protobuf.encode(sch, 'AllTypes', C, 'Layout', 'columns', 'Delimited', true), ...
  'Delimited', true);
asserts.isequal({R.f_string}, {'a', ''});
asserts.isequal(R(1).f_bytes, uint8([1 2]));
asserts.isequal({R.o_string}, {'x', ''});
asserts.isequal(R(1).r_string, {'p', 'q'});
asserts.isequal(R(1).r_bytes, {uint8(1), uint8('z')});
% Enum columns by name.
R = protobuf.decode(sch, 'AllTypes', protobuf.encode(sch, 'AllTypes', struct('f_enum', {{'RED'; 'BLUE'}}), ...
  'Layout', 'columns', 'Delimited', true), 'Delimited', true);
asserts.isequal([R.f_enum], int32([1 -3]));
%=============================================================================
% Wrappers and time values in columns: missing values, double given for integer wrappers.
wkt = protobuf.load([DATA, '/well_known.proto']);
t = datetime(2026, 11, 12, 10, 30, 0, 'TimeZone', 'UTC');
C = struct('at', [t; NaT('TimeZone', 'UTC')], 'elapsed', [seconds(1.5); NaN], 'level', [2.5; NaN], 'count', ...
  [7.6; NaN], ...
  'label', {{'a'; ''}});
bytes = protobuf.encode(wkt, 'Reading', C, 'Layout', 'columns', 'Delimited', true);
[R, P] = protobuf.decode(wkt, 'Reading', bytes, 'Delimited', true, 'Layout', 'columns', 'MissingAsNaN', true);
asserts.isequal(R.count(1), 8);
asserts.istrue(isnan(R.count(2)));
asserts.isequal(P.count, [true; false]);
asserts.isequal(P.label, [true; false]);
asserts.isequal(P.at, [true; false]);
R = protobuf.decode(wkt, 'Reading', bytes, 'Delimited', true, 'Layout', 'columns');
asserts.isequal(R.count, int32([8; 0]));
asserts.isequal(R.label, {'a'; ''});
S = protobuf.decode(wkt, 'Reading', protobuf.encode(wkt, 'Reading', struct('samples', single([1 2]), ...
  'label', 'x', 'marks', [t, t + 1])));
asserts.isequal(S.samples, single([1 2]));
asserts.isequal(S.label, 'x');
asserts.isequal(numel(S.marks), 2);
S = protobuf.decode(wkt, 'Reading', protobuf.encode(wkt, 'Reading', struct('samples', {{single(1), single(2)}})));
asserts.isequal(S.samples, single([1 2]));
%=============================================================================
% Unknown fields with a field selection, in both layouts.
older = protobuf.load(['syntax = "proto3"; package nelson.test.sensors; message SensorSample { int64 ', ...
  'timestamp_ms = 1; }'], ...
  'Format', 'text');
bytes = protobuf.encode(sch, 'SensorSample', struct('timestamp_ms', {1, 2}, 'status', {3, 4}), 'Delimited', true);
S = protobuf.decode(older, 'SensorSample', bytes, 'Delimited', true, 'KeepUnknown', true, 'Fields', 'timestamp_ms');
asserts.isequal(fieldnames(S), {'timestamp_ms'; 'UnknownFields'});
asserts.isequal(S(2).UnknownFields, uint8([16 4]));
S = protobuf.decode(older, 'SensorSample', uint8([]), 'Delimited', true, 'KeepUnknown', true, 'Fields', 'timestamp_ms');
asserts.isequal(size(S), [1 0]);
asserts.isequal(fieldnames(S), {'timestamp_ms'; 'UnknownFields'});
C = protobuf.decode(older, 'SensorSample', bytes, 'Delimited', true, 'KeepUnknown', true, 'Layout', 'columns');
asserts.isequal(C.UnknownFields, {uint8([16 3]); uint8([16 4])});
again = protobuf.encode(older, 'SensorSample', C, 'Layout', 'columns', 'Delimited', true);
asserts.isequal(again, bytes);
% Repeated message fields and their empty value.
S = protobuf.decode(sch, 'AllTypes', protobuf.encode(sch, 'AllTypes', struct('samples', ...
  struct('timestamp_ms', {1, 2}))));
asserts.isequal([S.samples.timestamp_ms], int64([1 2]));
S = protobuf.decode(sch, 'AllTypes', uint8([]), 'KeepUnknown', true);
asserts.isequal(size(S.samples), [1 0]);
asserts.istrue(isfield(S.samples, 'UnknownFields'));
