def strip(text):
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c in '"\'':
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == '\\' else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith('//', i):
            i = text.find('\n', i)
            i = n if i < 0 else i
        elif text.startswith('/*', i):
            i = text.index('*/', i) + 2
        else:
            out.append(c)
            i += 1
    lines = [line.rstrip() for line in ''.join(out).split('\n')]
    return '\n'.join(line for line in lines if line.strip()) + '\n'


def main():
    module_dir, source = sys.argv[1], sys.argv[2]
    version = re.search(r'protoc-([0-9.]+)', source.replace('\\', '/'))
    text = strip(open(source, encoding='utf-8').read())
    body = []
    for line in text.split('\n')[:-1]:
        escaped = line.replace('\\', '\\\\').replace('"', '\\"')
        body.append('        "' + escaped + '\\n"')
    out = HEADER % (version.group(1) if version else '') + '\n'.join(body) + ';\n' + FOOTER
    with open(module_dir + '/src/cpp/ProtoDescriptorText.cpp', 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(out)


main()
